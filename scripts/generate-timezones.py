"""Generate firmware future-rule lookup from pinned IANA TZif data.

Install the generator dependency with: python -m pip install tzdata==2026.5
The committed output makes normal firmware builds independent of Python tzdata.
TZif footers describe current/future recurring rules, not historical transitions.
"""
from importlib.resources import files
import json
from pathlib import Path
import tzdata

EXPECTED_VERSION = "2026.5"
if tzdata.__version__ != EXPECTED_VERSION:
    raise RuntimeError(f"Expected tzdata {EXPECTED_VERSION}, got {tzdata.__version__}")

root = Path(__file__).resolve().parents[1]
zone_root = files("tzdata.zoneinfo")
zones = files("tzdata").joinpath("zones").read_text(encoding="utf-8").splitlines()
entries = []
for name in sorted(set(zones)):
    data = zone_root.joinpath(*name.split("/")).read_bytes()
    if data[:4] != b"TZif" or data[4:5] not in (b"2", b"3", b"4"):
        raise RuntimeError(f"Unsupported TZif format: {name}")
    if not data.endswith(b"\n"):
        raise RuntimeError(f"Missing TZif footer: {name}")
    rule = data.rsplit(b"\n", 2)[1].decode("ascii")
    if not rule:
        raise RuntimeError(f"Missing recurring timezone rule: {name}")
    entries.append((name, rule))

header = f"""// Generated by scripts/generate-timezones.py; do not edit.
// Python tzdata {tzdata.__version__}; IANA release {tzdata.IANA_VERSION}.
// IANA timezone data is in the public domain.
#include "timezone_lookup.h"
#include <string.h>
typedef struct {{ const char *name; const char *rule; }} timezone_entry_t;
static const timezone_entry_t zones[] = {{
"""
lines = [f"  {{{json.dumps(name)}, {json.dumps(rule)}}},\n" for name, rule in entries]
footer = """};
const char *diy_timezone_posix(const char *name) {
  if (!name) return NULL;
  for (unsigned i = 0; i < sizeof(zones) / sizeof(zones[0]); ++i)
    if (!strcmp(name, zones[i].name)) return zones[i].rule;
  return NULL;
}
"""
target = root / "firmware/esp32-s3/src/timezone_lookup.c"
target.write_text(header + "".join(lines) + footer, encoding="utf-8", newline="\n")
print(f"Generated {len(entries)} zones from IANA {tzdata.IANA_VERSION}")
